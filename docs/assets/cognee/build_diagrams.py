"""Build editable SVG + JSON diagrams. Render JSON to PNG with render_diagrams.ps1.

Python standard library only. Diagrams explain product/component flows, not call graphs.
"""
import json
from pathlib import Path
from html import escape

ROOT = Path(__file__).resolve().parent
PALETTE = {"blue": "#eaf2ff", "green": "#e8f5ef", "gold": "#fff4d9", "purple": "#f0ecff", "red": "#fceceb", "gray": "#eef2f6"}


class Diagram:
    def __init__(self, name, title, subtitle, height=1050):
        self.data = dict(name=name, title=title, subtitle=subtitle, footer="Cognee 1.6.0 · 主流程示意 · 默认能力与可选能力见正文", width=1800, height=height, boxes=[], arrows=[], notes=[])

    def box(self, key, x, y, title, lines, color="blue", w=500, h=160):
        self.data["boxes"].append(dict(key=key, x=x, y=y, w=w, h=h, title=title, lines=lines, fill=PALETTE[color]))
        return self

    def arrow(self, points, label="", lx=0, ly=0):
        self.data["arrows"].append(dict(points=points, label=label, lx=lx, ly=ly))
        return self

    def note(self, x, y, text):
        self.data["notes"].append(dict(x=x, y=y, text=text))
        return self

    def save(self):
        d = self.data
        (ROOT / (d["name"] + ".json")).write_text(json.dumps(d, ensure_ascii=False, indent=2), encoding="utf-8")
        s = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{d["width"]}" height="{d["height"]}" viewBox="0 0 {d["width"]} {d["height"]}">', '<defs><marker id="arrow" markerWidth="10" markerHeight="10" refX="8" refY="3" orient="auto" markerUnits="strokeWidth"><path d="M0,0 L0,6 L8,3 z" fill="#66788f"/></marker></defs>', '<rect width="100%" height="100%" fill="#ffffff"/>']
        def txt(x, y, text, size=25, bold=False, color="#20334b"):
            return f'<text x="{x}" y="{y}" font-family="Microsoft YaHei UI, sans-serif" font-size="{size}" font-weight="{700 if bold else 400}" fill="{color}">{escape(text)}</text>'
        s += [txt(65, 67, d["title"], 38, True), txt(65, 115, d["subtitle"], 25, color="#5d7087")]
        for a in d["arrows"]:
            p = " ".join(f"{x},{y}" for x,y in a["points"])
            s.append(f'<polyline points="{p}" fill="none" stroke="#66788f" stroke-width="3" marker-end="url(#arrow)"/>')
            if a["label"]:
                s.append(txt(a["lx"], a["ly"], a["label"], 22))
        for b in d["boxes"]:
            s += [f'<rect x="{b["x"]}" y="{b["y"]}" width="{b["w"]}" height="{b["h"]}" rx="14" fill="{b["fill"]}" stroke="#c7d4e2"/>', txt(b["x"]+22,b["y"]+43,b["title"],29,True)]
            for i,line in enumerate(b["lines"]):
                s.append(txt(b["x"]+22,b["y"]+83+33*i,line,24))
        for n in d["notes"]:
            s.append(txt(n["x"],n["y"],n["text"],24,color="#5d7087"))
        s.append(txt(65,d["height"]-25,"Cognee 1.6.0 · 主流程示意 · 默认能力与可选能力见正文",20,color="#718198"))
        s.append('</svg>')
        (ROOT / (d["name"] + ".svg")).write_text("\n".join(s),encoding="utf-8")


